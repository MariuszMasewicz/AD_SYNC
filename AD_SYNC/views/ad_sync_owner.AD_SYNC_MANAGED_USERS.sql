pro    CREATE OR REPLACE VIEW ad_sync_owner.AD_SYNC_MANAGED_USERS

CREATE OR REPLACE FORCE EDITIONABLE VIEW "AD_SYNC_OWNER"."AD_SYNC_MANAGED_USERS" (
  "USERNAME"
 ,"USER_ID"
 ,"PASSWORD"
 ,"ACCOUNT_STATUS"
 ,"LOCK_DATE"
 ,"EXPIRY_DATE"
 ,"DEFAULT_TABLESPACE"
 ,"TEMPORARY_TABLESPACE"
 ,"LOCAL_TEMP_TABLESPACE"
 ,"CREATED"
 ,"PROFILE"
 ,"INITIAL_RSRC_CONSUMER_GROUP"
 ,"EXTERNAL_NAME"
 ,"PASSWORD_VERSIONS"
 ,"EDITIONS_ENABLED"
 ,"AUTHENTICATION_TYPE"
 ,"PROXY_ONLY_CONNECT"
 ,"COMMON"
 ,"LAST_LOGIN"
 ,"ORACLE_MAINTAINED"
 ,"INHERITED"
 ,"DEFAULT_COLLATION"
 ,"IMPLICIT"
 ,"ALL_SHARD"
 ,"PASSWORD_CHANGE_DATE"
) DEFAULT COLLATION "USING_NLS_COMP" AS
  SELECT "USERNAME"
        ,"USER_ID"
        ,"PASSWORD"
        ,"ACCOUNT_STATUS"
        ,"LOCK_DATE"
        ,"EXPIRY_DATE"
        ,"DEFAULT_TABLESPACE"
        ,"TEMPORARY_TABLESPACE"
        ,"LOCAL_TEMP_TABLESPACE"
        ,"CREATED"
        ,"PROFILE"
        ,"INITIAL_RSRC_CONSUMER_GROUP"
        ,"EXTERNAL_NAME"
        ,"PASSWORD_VERSIONS"
        ,"EDITIONS_ENABLED"
        ,"AUTHENTICATION_TYPE"
        ,"PROXY_ONLY_CONNECT"
        ,"COMMON"
        ,"LAST_LOGIN"
        ,"ORACLE_MAINTAINED"
        ,"INHERITED"
        ,"DEFAULT_COLLATION"
        ,"IMPLICIT"
        ,"ALL_SHARD"
        ,"PASSWORD_CHANGE_DATE"
    FROM SYS.DBA_USERS
   WHERE USERNAME LIKE AD_SYNC_OWNER.AD_SYNC_TOOLS.GET_PARAM_VALUE('USERNAME_PREFIX')
                       || '%'
      OR USERNAME IN (
    SELECT USERNAME
      FROM AD_SYNC_OWNER.AD_SYNC_USERS_FOR_SERVICES
  )                  
   --ORDER BY USERNAME
  ;